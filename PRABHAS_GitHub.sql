IF DB_ID('restaurant') IS NOT NULL
BEGIN
    ALTER DATABASE restaurant SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE restaurant;
END
GO
CREATE DATABASE restaurant;
GO
USE restaurant;
GO
CREATE TABLE restaurant(
 reataurantID INT PRIMARY KEY,
    restaurantname VARCHAR(50),
    address VARCHAR(50),
    contact VARCHAR(50),
    rating DECIMAL(3,1)
);

CREATE TABLE custmer(
    custmerID INT PRIMARY KEY,
    mobile BIGINT,
    email VARCHAR(50),
    address VARCHAR(50),
    name VARCHAR(50)
);

CREATE TABLE payment(
    paymentId INT PRIMARY KEY,
    amount INT,
    type VARCHAR(50),
    date DATE,
    discount DECIMAL(5,2)
);

CREATE TABLE food(
    foodID INT PRIMARY KEY,
    name VARCHAR(50),
    type VARCHAR(50),
    QTY VARCHAR(50),
    price INT
);

CREATE TABLE staff(
    staffID INT PRIMARY KEY,
    name VARCHAR(50),
    orders INT,
    rating DECIMAL(2,1),
    salarey INT
);
